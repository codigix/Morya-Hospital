// Regenerates sitemap.xml from data/blogs.json (blog URLs) + existing core pages.
// Usage: node scripts/update-sitemap-dynamic.js          (one-off)
//        node scripts/update-sitemap-dynamic.js --watch  (re-run whenever blogs.json changes)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITEMAP = path.join(ROOT, 'sitemap.xml');
const BLOGS = path.join(ROOT, 'data', 'blogs.json');
const BASE = 'https://morayamultispecialitycharitablehospital.com';

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// blogs.json uses dd/mm/yyyy; return ISO or null
function toIso(d) {
  const m = /^(\d{1,2})\/(\d{1,2})\/(\d{4})$/.exec(d || '');
  if (m) return `${m[3]}-${m[2].padStart(2, '0')}-${m[1].padStart(2, '0')}T00:00:00+00:00`;
  const t = Date.parse(d);
  return isNaN(t) ? null : new Date(t).toISOString();
}

function entry(loc, lastmod, priority) {
  return `  <url>\n    <loc>${esc(loc)}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <priority>${priority}</priority>\n  </url>`;
}

function build() {
  const blogs = JSON.parse(fs.readFileSync(BLOGS, 'utf8'));
  const old = fs.existsSync(SITEMAP) ? fs.readFileSync(SITEMAP, 'utf8') : '';

  // Keep core pages; remember previous lastmod of blog URLs
  const prevLastmod = {};
  const core = [];
  for (const m of old.matchAll(/<url>([\s\S]*?)<\/url>/g)) {
    const loc = (/<loc>([^<]+)<\/loc>/.exec(m[1]) || [])[1]?.trim();
    if (!loc) continue;
    const lm = (/<lastmod>([^<]+)<\/lastmod>/.exec(m[1]) || [])[1];
    const pr = (/<priority>([^<]+)<\/priority>/.exec(m[1]) || [])[1] || '0.80';
    prevLastmod[loc] = lm;
    const isBlog = loc.includes('/blog.html/') || loc.includes('blog-details.html');
    const isIndex = loc.endsWith('/index.html'); // duplicate of "/"
    if (!isBlog && !isIndex) core.push({ loc, lm: lm || new Date().toISOString(), pr });
  }

  const now = new Date().toISOString();
  const seen = new Set();
  const blogEntries = [];
  for (const b of blogs) {
    const slug = String(b.slug || '').trim().replace(/\.html$/, '');
    if (!slug || seen.has(slug)) continue;
    seen.add(slug);
    const loc = `${BASE}/blog.html/${encodeURIComponent(slug)}.html`;
    blogEntries.push(entry(loc, b.lastmod || prevLastmod[loc] || toIso(b.date) || now, '0.64'));
  }

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
<!-- Auto-generated by scripts/update-sitemap-dynamic.js from data/blogs.json. Do not edit blog URLs by hand. -->
${core.map(c => entry(c.loc, c.lm, c.pr)).join('\n')}
${blogEntries.join('\n')}
</urlset>
`;
  if (xml !== old) fs.writeFileSync(SITEMAP, xml, 'utf8');
  console.log(`sitemap.xml ${xml !== old ? 'updated' : 'unchanged'}: ${core.length} core pages, ${blogEntries.length} blog pages`);
}

build();

if (process.argv.includes('--watch')) {
  let timer;
  fs.watch(BLOGS, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try { build(); } catch (e) { console.error('Invalid blogs.json:', e.message); }
    }, 300);
  });
  console.log('Watching data/blogs.json ...');
}
